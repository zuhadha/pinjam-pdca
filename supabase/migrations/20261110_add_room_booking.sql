-- Migration: Room booking module (merged from the Laravel "COE Rooms" app)
-- Created: 2026-11-10
--
-- Tables
--   rooms              bookable rooms                       (MySQL: rooms)
--   room_images        room photos in storage bucket         (MySQL: room_images)
--   room_reservations  one row per booking form submission   (MySQL: borrow_rooms parent rows)
--   room_bookings      one row per date of a reservation     (MySQL: borrow_rooms + recurring instances)
--
-- Rules
--   * No admin approval. A new booking is 'confirmed' when its room and time are free,
--     otherwise 'waitlisted'. Admin later cancels one and promotes a waitlisted one.
--   * Two confirmed bookings for the same room can never overlap. The exclusion constraint
--     enforces this inside the database, so concurrent submissions are safe.
--   * Times are Asia/Jakarta wall-clock values stored as DATE + TIME (no time zone),
--     the same way the Laravel app stored them. This keeps the MySQL import a straight copy.
--   * IDs are BIGINT identities so old MySQL IDs can be kept in legacy_id columns.
--
-- Access
--   RLS is on with no policies. Only the service role (server actions) reads and writes.
--   The public calendar is served by server code that strips phone and email.

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ==================================================
-- 1. rooms
-- ==================================================
CREATE TABLE IF NOT EXISTS rooms (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  area        TEXT,                                   -- location, e.g. 'Office Lt.2'
  max_people  INTEGER CHECK (max_people IS NULL OR max_people > 0),
  facilities  TEXT,                                   -- free text, one facility per line
  status      TEXT NOT NULL DEFAULT 'available'
              CHECK (status IN ('available', 'maintenance')),
  sort_order  INTEGER NOT NULL DEFAULT 0,
  legacy_id   BIGINT UNIQUE,                          -- rooms.id in the old MySQL database
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at  TIMESTAMPTZ                             -- soft delete keeps booking history intact
);

CREATE INDEX IF NOT EXISTS idx_rooms_active ON rooms (sort_order, name) WHERE deleted_at IS NULL;

-- ==================================================
-- 2. room_images
-- ==================================================
CREATE TABLE IF NOT EXISTS room_images (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id        BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
  storage_path   TEXT NOT NULL,                       -- path inside the 'room-images' bucket
  public_url     TEXT NOT NULL,
  display_order  INTEGER NOT NULL DEFAULT 0,
  legacy_id      BIGINT UNIQUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_room_images_room ON room_images (room_id, display_order);

-- ==================================================
-- 3. room_reservations (who booked, what for, how it repeats)
-- ==================================================
CREATE TABLE IF NOT EXISTS room_reservations (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  borrower_name             TEXT NOT NULL,
  department                TEXT NOT NULL,
  phone_number              TEXT NOT NULL,
  email                     TEXT,
  agenda                    TEXT NOT NULL,          -- MySQL: activity_category
  participants              TEXT,
  people_count              INTEGER CHECK (people_count IS NULL OR people_count > 0),
  notes                     TEXT,
  recurrence_type           TEXT NOT NULL DEFAULT 'none'
                            CHECK (recurrence_type IN ('none', 'daily', 'weekly', 'monthly')),
  recurrence_weekdays       SMALLINT[],             -- weekly only, ISO 1 = Monday .. 7 = Sunday
  recurrence_skip_weekends  BOOLEAN NOT NULL DEFAULT FALSE, -- daily only
  recurrence_until          DATE,
  recurrence_count          INTEGER CHECK (recurrence_count IS NULL OR recurrence_count > 0),
  manage_token              TEXT NOT NULL UNIQUE,   -- borrower's link to view or cancel
  created_by                UUID REFERENCES users(id) ON DELETE SET NULL, -- set when an admin booked it
  legacy_id                 BIGINT UNIQUE,          -- borrow_rooms.id of the parent row in MySQL
  created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at                TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ==================================================
-- 4. room_bookings (one date, one room, one time range)
-- ==================================================
CREATE TABLE IF NOT EXISTS room_bookings (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id     BIGINT NOT NULL REFERENCES room_reservations(id) ON DELETE CASCADE,
  room_id            BIGINT NOT NULL REFERENCES rooms(id),
  booking_date       DATE NOT NULL,
  start_time         TIME NOT NULL,
  end_time           TIME NOT NULL,
  status             TEXT NOT NULL DEFAULT 'confirmed'
                     CHECK (status IN ('confirmed', 'waitlisted', 'cancelled')),
  status_changed_at  TIMESTAMPTZ,
  cancelled_by       TEXT CHECK (cancelled_by IN ('admin', 'borrower')),
  cancel_reason      TEXT,
  legacy_id          BIGINT UNIQUE,                 -- borrow_rooms.id in MySQL
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  during             TSRANGE GENERATED ALWAYS AS
                     (tsrange(booking_date + start_time, booking_date + end_time, '[)')) STORED,
  CONSTRAINT room_bookings_time_order CHECK (end_time > start_time),
  CONSTRAINT room_bookings_no_overlap
    EXCLUDE USING gist (room_id WITH =, during WITH &&) WHERE (status = 'confirmed')
);

CREATE INDEX IF NOT EXISTS idx_room_bookings_date ON room_bookings (booking_date, room_id);
CREATE INDEX IF NOT EXISTS idx_room_bookings_reservation ON room_bookings (reservation_id);
CREATE INDEX IF NOT EXISTS idx_room_bookings_waitlist
  ON room_bookings (room_id, booking_date, created_at) WHERE status = 'waitlisted';

