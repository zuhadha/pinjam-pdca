             WHERE table_schema = 'storage' AND table_name = 'buckets') THEN
    INSERT INTO storage.buckets (id, name, public)
    VALUES ('room-images', 'room-images', TRUE)
    ON CONFLICT (id) DO NOTHING;
  END IF;
END $$;
