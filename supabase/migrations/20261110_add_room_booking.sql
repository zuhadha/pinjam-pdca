CREATE TRIGGER update_room_bookings_updated_at BEFORE UPDATE ON room_bookings
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- ==================================================
-- 6. create_room_reservation(): insert a reservation and its dates in one transaction.
--    Each date is tried as 'confirmed'; if it overlaps a confirmed booking the
--    exclusion constraint fires and the date is stored as 'waitlisted' instead.
--
--    p_reservation: { borrower_name, department, phone_number, email, agenda, participants,
--                     people_count, notes, recurrence_type, recurrence_weekdays,
--                     recurrence_skip_weekends, recurrence_until, recurrence_count,
--                     manage_token, created_by }
--    p_slots:       [{ room_id, date: 'YYYY-MM-DD', start: 'HH:MM', end: 'HH:MM' }, ...]
-- ==================================================
CREATE OR REPLACE FUNCTION create_room_reservation(p_reservation JSONB, p_slots JSONB)
RETURNS TABLE (reservation_id BIGINT, booking_id BIGINT, booking_date DATE, status TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_reservation_id BIGINT;
  v_slot JSONB;
  v_booking_id BIGINT;
  v_status TEXT;
  v_room_id BIGINT;
BEGIN
  IF jsonb_typeof(p_slots) <> 'array' OR jsonb_array_length(p_slots) = 0 THEN
    RAISE EXCEPTION 'No dates to book' USING ERRCODE = '22023';
  END IF;

  -- Every room must exist, not be deleted and not be under maintenance
  FOR v_room_id IN SELECT DISTINCT (s->>'room_id')::BIGINT FROM jsonb_array_elements(p_slots) s LOOP
    PERFORM 1 FROM rooms r
      WHERE r.id = v_room_id AND r.deleted_at IS NULL AND r.status = 'available';
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Room % is not available for booking', v_room_id USING ERRCODE = '22023';
    END IF;
  END LOOP;

  INSERT INTO room_reservations (
    borrower_name, department, phone_number, email, agenda, participants, people_count, notes,
    recurrence_type, recurrence_weekdays, recurrence_skip_weekends, recurrence_until,
    recurrence_count, manage_token, created_by
  ) VALUES (
    p_reservation->>'borrower_name',
    p_reservation->>'department',
    p_reservation->>'phone_number',
    NULLIF(p_reservation->>'email', ''),
    p_reservation->>'agenda',
    NULLIF(p_reservation->>'participants', ''),
    NULLIF(p_reservation->>'people_count', '')::INTEGER,
    NULLIF(p_reservation->>'notes', ''),
    COALESCE(p_reservation->>'recurrence_type', 'none'),
    CASE WHEN jsonb_typeof(p_reservation->'recurrence_weekdays') = 'array'
         THEN ARRAY(SELECT jsonb_array_elements_text(p_reservation->'recurrence_weekdays')::SMALLINT)
    END,
    COALESCE((p_reservation->>'recurrence_skip_weekends')::BOOLEAN, FALSE),
    NULLIF(p_reservation->>'recurrence_until', '')::DATE,
    NULLIF(p_reservation->>'recurrence_count', '')::INTEGER,
    p_reservation->>'manage_token',
    NULLIF(p_reservation->>'created_by', '')::UUID
  )
  RETURNING id INTO v_reservation_id;

  FOR v_slot IN SELECT * FROM jsonb_array_elements(p_slots) LOOP
    BEGIN
      INSERT INTO room_bookings (reservation_id, room_id, booking_date, start_time, end_time, status)
      VALUES (
        v_reservation_id,
        (v_slot->>'room_id')::BIGINT,
        (v_slot->>'date')::DATE,
        (v_slot->>'start')::TIME,
        (v_slot->>'end')::TIME,
        'confirmed'
      )
      RETURNING id INTO v_booking_id;
      v_status := 'confirmed';
    EXCEPTION WHEN exclusion_violation THEN
      INSERT INTO room_bookings (reservation_id, room_id, booking_date, start_time, end_time, status)
      VALUES (
        v_reservation_id,
        (v_slot->>'room_id')::BIGINT,
        (v_slot->>'date')::DATE,
        (v_slot->>'start')::TIME,
        (v_slot->>'end')::TIME,
        'waitlisted'
      )
      RETURNING id INTO v_booking_id;
      v_status := 'waitlisted';
    END;

    reservation_id := v_reservation_id;
    booking_id := v_booking_id;
    booking_date := (v_slot->>'date')::DATE;
    status := v_status;
    RETURN NEXT;
  END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION create_room_reservation(JSONB, JSONB) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON FUNCTION create_room_reservation(JSONB, JSONB) FROM anon, authenticated';
    EXECUTE 'GRANT EXECUTE ON FUNCTION create_room_reservation(JSONB, JSONB) TO service_role';
  END IF;
END $$;

